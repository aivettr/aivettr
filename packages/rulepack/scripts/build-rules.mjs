/**
 * 构建脚本：把 rules/*.yaml 打包为 dist/rules-data.js。
 * 设计理由：内置规则随 JS 实体分发（CLI 直接可用、ncc 可整体打包），
 * 同时保留 .yaml 源文件（pack 结构可独立分发、规则资产可平移）。
 */

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";

const rulesDir = new URL("../rules/", import.meta.url);
const distDir = new URL("../dist/", import.meta.url);

const names = (await readdir(rulesDir))
  .filter((n) => n.endsWith(".yaml") || n.endsWith(".yml"))
  .sort();

const data = {};
for (const name of names) {
  data[name] = await readFile(new URL(name, rulesDir), "utf8");
}

await mkdir(distDir, { recursive: true });
const body =
  "// AUTO-GENERATED by scripts/build-rules.mjs — do not edit by hand\n" +
  "export const BUILTIN_YAML = Object.freeze(" +
  JSON.stringify(data, null, 2) +
  ");\n";
await writeFile(new URL("rules-data.js", distDir), body);
console.log(`rules-data.js: ${names.length} rules (${names.join(", ")})`);
